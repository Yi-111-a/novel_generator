def main():
    assert len(CH) == 46, len(CH)
    con = sqlite3.connect(DB); con.row_factory = sqlite3.Row; cur = con.cursor()

    # 1) 脊梁理顺：青冥界并成整卷2 —— blueprint 11->10（替换 修真上/下 为 青冥界）
    row = cur.execute("select id, body_full from world_bible_sections where section='outline_contract' and source='contract' order by id").fetchall()[-1]
    contract = json.loads(row["body_full"]); vb = contract.get("volume_blueprint") or []
    new_qm = {"title": QINGMING_VOL["title"], "short_goal": QINGMING_VOL["short_goal"], "obstacle": QINGMING_VOL["obstacle"],
              "conflict_chain": QINGMING_VOL["conflict_chain"], "key_twist": QINGMING_VOL["key_twist"],
              "gain_and_hook": QINGMING_VOL["gain_and_hook"], "allowed": QINGMING_VOL["allowed"],
              "shadow_only": QINGMING_VOL["shadow_only"], "forbidden": QINGMING_VOL["forbidden"]}
    if len(vb) == 11:   # [赘婿,修真上,修真下,末世上,...] -> [赘婿,青冥界,末世上,...]
        vb = [vb[0], new_qm] + vb[3:]
    elif len(vb) >= 2:  # 幂等/兜底：直接把 index1 设成青冥界
        vb[1] = new_qm
    contract["volume_blueprint"] = vb
    cur.execute("update world_bible_sections set body_full=? where id=?", (json.dumps(contract, ensure_ascii=False, indent=2), row["id"]))

    # 2) parts：seq2=青冥界；删 seq3(修真下)+其arcs；seq>=4 顺位上移
    p2 = cur.execute("select part_id from parts where sequence_order=2").fetchone()["part_id"]
    cur.execute("update parts set title=?, goal=?, region=? where part_id=?",
                (QINGMING_VOL["title"], QINGMING_VOL["short_goal"], "修真世界·青冥界（炼气-化神/三大仙门/魔道/坊市/命格司，专有名到该章落库）", p2))
    p3 = cur.execute("select part_id from parts where sequence_order=3").fetchone()
    if p3:
        cur.execute("delete from arcs where part_id=?", (p3["part_id"],))
        cur.execute("delete from parts where part_id=?", (p3["part_id"],))
        cur.execute("update parts set sequence_order=sequence_order-1 where sequence_order>=4")

    # 3) part2：删旧2 arcs，建5 幕 arc
    cur.execute("delete from chapter_plans where arc_id in (select arc_id from arcs where part_id=?)", (p2,))
    cur.execute("delete from arcs where part_id=?", (p2,))
    acts = [("幕一·倒叙冷开场", 3), ("幕二·入界与首单", 9), ("幕三·宗门少主", 12), ("幕四·界级阴谋", 14), ("幕五·结单与暗线", 8)]
    arc_ids = []
    for i, (atitle, tc) in enumerate(acts, 1):
        aid = f"arc_{uuid.uuid4().hex[:6]}"; arc_ids.append((aid, tc))
        cur.execute("insert into arcs (arc_id,part_id,sequence_order,title,summary,target_chapters,focus_agents,status) values (?,?,?,?,?,?,?,?)",
                    (aid, p2, i, atitle, QINGMING_VOL["short_goal"], tc, "[]", "active" if i == 1 else "planned"))

    def arc_for(seq):
        if seq <= 3: return arc_ids[0][0]
        if seq <= 12: return arc_ids[1][0]
        if seq <= 24: return arc_ids[2][0]
        if seq <= 38: return arc_ids[3][0]
        return arc_ids[4][0]

    # 4) 插 46 章 chapter_plans
    for c in CH:
        cur.execute(
            "insert into chapter_plans (chapter_id, arc_id, sequence_order, title, cast, location_ids,"
            " beat_goals, summary, reveal_gate, target_scenes, role, target_tension, dramatic_question,"
            " resolution_predicate, min_scenes, target_words, ending_hook, hook_type, pov_agent, exit_state,"
            " conflict_type, beat_povs, status, package_version)"
            " values (?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?)",
            (f"ch_{uuid.uuid4().hex[:6]}", arc_for(c["seq"]), c["seq"], c["title"],
             json.dumps(c["cast"], ensure_ascii=False), json.dumps(c["locs"], ensure_ascii=False),
             json.dumps(c["beats"], ensure_ascii=False), c["summary"], json.dumps([], ensure_ascii=False),
             len(c["beats"]) + 1, c["role"], c["tension"], c["dq"], "",
             max(2, len(c["beats"])), c["words"], c["hook"], "new_question", c["pov"], c["exit_state"],
             c["conflict"], json.dumps([c["pov"]] * len(c["beats"]), ensure_ascii=False), "planned", 1),
        )
    con.commit()

    print("卷2《青冥界·逆天改命》章纲已入库：5 幕 46 章；脊梁理顺(blueprint", len(vb), "卷)。")
    print("各卷:")
    for r in cur.execute("select sequence_order,title from parts order by sequence_order"):
        print(f"  卷{r['sequence_order']:>2} {r['title']}")
    print("卷2 各幕章数:")
    ac = con.cursor()
    for r in cur.execute("select a.arc_id,a.sequence_order,a.title,a.target_chapters from arcs a join parts p on a.part_id=p.part_id where p.sequence_order=2 order by a.sequence_order"):
        n = ac.execute("select count(*) from chapter_plans where arc_id=?", (r["arc_id"],)).fetchone()[0]
        print(f"  {r['title']}  目标{r['target_chapters']}章 / 实建{n}章")
    print("卷2 总章数:", cur.execute("select count(*) from chapter_plans cp join arcs a on cp.arc_id=a.arc_id join parts p on a.part_id=p.part_id where p.sequence_order=2").fetchone()[0])
    con.close()


if __name__ == "__main__":
    main()
