# 现有 6 个 part 的新 sequence_order（按 title 匹配，迁移保留其 arcs）
EXISTING_MOVE = {
    "实习工单": 1,
    "差评风暴": 2,
    "保修条款": 3,
    "互助会暗流": 9,
    "运营中枢": 11,
    "末位淘汰": 13,
}
# 新建的卷（seq -> blueprint index）
NEW_SEQS = [4, 5, 6, 7, 8, 10, 12, 14, 15, 16]


def main():
    con = sqlite3.connect(DB)
    con.row_factory = sqlite3.Row
    cur = con.cursor()

    assert len(VOLUMES) == 16, len(VOLUMES)

    existing = {r["title"]: r["part_id"] for r in cur.execute("select part_id,title,sequence_order from parts")}
    cur_count = cur.execute("select count(*) from parts").fetchone()[0]
    if cur_count >= 16:
        print("already >=16 parts, abort to stay idempotent")
        return

    # 1) 写 story_scale + volume_blueprint 到合同
    row = cur.execute(
        "select id, body_full from world_bible_sections where section='outline_contract' and source='contract' order by id"
    ).fetchall()[-1]
    contract = json.loads(row["body_full"])
    contract["story_scale"] = STORY_SCALE
    contract["volume_blueprint"] = VOLUMES
    cur.execute(
        "update world_bible_sections set body_full=? where id=?",
        (json.dumps(contract, ensure_ascii=False, indent=2), row["id"]),
    )
    print("contract updated: scale=zhutian(14-18), volume_blueprint=16")

    # 2) 迁移现有 part 的 sequence_order + 刷新 goal（标题匹配）
    for title, part_id in existing.items():
        seq = EXISTING_MOVE.get(title)
        if seq is None:
            print("WARN unmatched existing part:", title)
            continue
        v = VOLUMES[seq - 1]
        cur.execute(
            "update parts set sequence_order=?, goal=? where part_id=?",
            (seq, v["short_goal"], part_id),
        )
        print(f"moved part [{title}] -> seq {seq}")

    # 3) 新建 10 个 part + 每个 2 个 arc 骨架
    for seq in NEW_SEQS:
        v = VOLUMES[seq - 1]
        pid = uid("part")
        region = "本卷世界名到本卷再正式命名落库" if 4 <= seq <= 8 else ""
        cur.execute(
            "insert into parts (part_id, sequence_order, title, goal, region, key_twist, new_crisis_hook, reveal_node_ids, status)"
            " values (?,?,?,?,?,?,?,?,?)",
            (pid, seq, v["title"], v["short_goal"], region, v["key_twist"], v["gain_and_hook"], "[]", "planned"),
        )
        for a in (1, 2):
            aid = uid("arc")
            atitle = f"{v['title']}·其{a}"
            cur.execute(
                "insert into arcs (arc_id, part_id, sequence_order, title, summary, target_chapters, focus_agents, status)"
                " values (?,?,?,?,?,?,?,?)",
                (aid, pid, a, atitle, v["short_goal"], 6, "[]", "planned"),
            )
        print(f"created part [{v['title']}] seq {seq} (+2 arc skeletons)")

    con.commit()

    # 验证
    print("\n=== 验证 ===")
    for r in cur.execute("select sequence_order,title,status from parts order by sequence_order"):
        n_arc = cur.execute("select count(*) from arcs a join parts p on a.part_id=p.part_id where p.sequence_order=?", (r["sequence_order"],)).fetchone()[0]
        print(f"  卷{r['sequence_order']:>2} {r['title']}  [{r['status']}] arcs={n_arc}")
    print("total parts:", cur.execute("select count(*) from parts").fetchone()[0])
    print("total arcs:", cur.execute("select count(*) from arcs").fetchone()[0])
    con.close()


if __name__ == "__main__":
    main()
