def main():
    assert len(VOLUMES) == 11, len(VOLUMES)
    con = sqlite3.connect(DB); con.row_factory = sqlite3.Row; cur = con.cursor()

    # 1) scale + blueprint
    row = cur.execute("select id, body_full from world_bible_sections where section='outline_contract' and source='contract' order by id").fetchall()[-1]
    contract = json.loads(row["body_full"])
    contract["story_scale"] = SCALE
    contract["volume_blueprint"] = VOLUMES
    # 记下「每卷1-2章渗暗线、不预设收尾」的原则
    pr = contract.get("principles") or []
    note = "中转站/公司=暗线：每卷只留1-2章渗公司线（差评/陌生工号/测试品/黑市/命数收割），其余整卷一个世界的独立故事；不预设收尾，暗线收口写到再定。"
    if note not in pr: pr = [note] + [p for p in pr if "中转站" not in str(p)]
    contract["principles"] = pr
    cur.execute("update world_bible_sections set body_full=? where id=?",
                (json.dumps(contract, ensure_ascii=False, indent=2), row["id"]))

    # 2) vol1 保留；更新其 goal=新blueprint短目标
    v1 = cur.execute("select part_id from parts where sequence_order=1").fetchone()["part_id"]
    cur.execute("update parts set title=?, goal=? where part_id=?", (VOLUMES[0]["title"], VOLUMES[0]["short_goal"], v1))

    # 3) 删 seq>=2 的 parts 及其 arcs（已确认无 chapter_plans）
    old = [r["part_id"] for r in cur.execute("select part_id from parts where sequence_order>=2")]
    for p in old:
        cur.execute("delete from arcs where part_id=?", (p,))
        cur.execute("delete from parts where part_id=?", (p,))

    # 4) 新建 seq2-11
    for i, v in enumerate(VOLUMES[1:], start=2):
        pid_new = f"part_{uuid.uuid4().hex[:6]}"
        cur.execute("insert into parts (part_id,sequence_order,title,goal,region,key_twist,new_crisis_hook,reveal_node_ids,status) values (?,?,?,?,?,?,?,?,?)",
                    (pid_new, i, v["title"], v["short_goal"], "本卷世界名到本卷再正式命名落库", v["key_twist"], v["gain_and_hook"], "[]", "planned"))
        for a in (1, 2):
            cur.execute("insert into arcs (arc_id,part_id,sequence_order,title,summary,target_chapters,focus_agents,status) values (?,?,?,?,?,?,?,?)",
                        (f"arc_{uuid.uuid4().hex[:6]}", pid_new, a, f"{v['title']}·其{a}", v["short_goal"], 6, "[]", "planned"))
    con.commit()

    print("scale=zhutian_world(11-20), blueprint=11, 公司线降为暗线，砍掉终局卷")
