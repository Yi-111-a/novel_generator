# -*- coding: utf-8 -*-
"""共享 prompt 增补 —— 跨写作 / 大纲 / 删减各路径复用，单一来源。

ANTI_AI_FLAVOR_GUIDANCE：用户手工调出的"去 AI 味"硬约束。注入到所有写作（正文 / 删减）
与大纲（Part / Arc / Chapter / 下一章章纲）prompt 的 system 段尾部。
"""
from __future__ import annotations

ANTI_AI_FLAVOR_GUIDANCE = """
【严格禁止以下句式 / 词汇 / 起名 / 默认世界观词】

句式套路：
- 不要写「X 拉得很长 / 压得很低 / 沉得很重」之类「动词+得+很+形容词」结构
- 不要写「像是有什么 / 像是被什么 / 某种古老的 / 像灌了 X」之类模糊比喻
- 不要写「每一次呼吸都 / 每一步都踩在 / 不受控制地」之类排比量化
- 不要写「发出 X 的 X / 爆发出震耳欲聋的 / 空气中弥漫着」之类声响修辞
- 不要写「细密的汗珠 / 靠在椅背上 / 听见自己 / 深吸一口气」之类感官内观
- 不要写「<人物>的指尖 / 嘴角 / 掌心 / 瞳孔 + 动作」，用整体动作描写
- 起名禁用「沈砚 / 陈默 / 林默 / 林渊 / 楚云 / 杨墨」等套路名
- 禁用「浮石 / 铁律 / 天枢 / 铜星 / 沉钟谷 / 旧大陆」等默认世界观词

高频副词 / 形容词癖（每段最多用 1 次）：
- 猛地、骤然、缓缓、深吸、纹丝不动、若有若无、咬紧牙关、扑面而来、话音未落
- 锈蚀、苔藓、沙哑、浑浊、死寂、暗影、细密、若有若无

结构习惯：
- 破折号「——」每千字最多 1 个
- 比喻句（含 "像 / 像是 / 仿佛 / 好像"）每段最多 1 句
- 句子长短交错，必须有 3-5 字短句穿插，避免句子都是 15-25 字
- 用具体的拟声词（砰 / 咯吱 / 哐当），不要用「沉闷 / 嗡鸣 / 嘶吼」之类抽象修饰
- 比喻要个人化、有新鲜感，不能用「古老的 / 不知名的 / 某种」这种空形容
"""


def with_anti_ai(system_prompt: str) -> str:
    """把"去 AI 味"硬约束追加到任何 system prompt 末尾。"""
    return (system_prompt or "").rstrip() + "\n\n" + ANTI_AI_FLAVOR_GUIDANCE
